"""Interfaces to be implemented by platform-specific QVAC and WDK adapters."""
from typing import Protocol, Mapping, Any

class InferencePort(Protocol):
    def infer(self, prompt: str, context: Mapping[str, Any]) -> str: ...

class WalletPort(Protocol):
    def prepare_transaction(self, intent: Mapping[str, str]) -> Mapping[str, str]: ...
    def request_local_approval(self, intent_id: str) -> bool: ...
    def sign_approved_transaction(self, intent_id: str) -> str: ...

class LocalEventStorePort(Protocol):
    def append_event(self, event_id: str, event_type: str, payload: bytes) -> None: ...
    def list_pending_events(self, limit: int) -> list: ...
